# Lightroom-style editor: every panel, exact values, curve, wheel, presets with Amount, undo/redo, menu tools, .xmp in and out.
import io, zipfile, sys
from playwright.sync_api import sync_playwright
errs = []
FIX = '/home/claude/canva-lite/scripts/smoke/fixtures/golden-moody.xmp'
WK = 'wk' in sys.argv
def px(pg):
    return pg.evaluate("""() => { const c = document.querySelector('canvas.lower-canvas'); const d = c.getContext('2d').getImageData(c.width*0.35|0, c.height*0.45|0, 1, 1).data; return [d[0], d[1], d[2]]; }""")
def val(pg, panel, label):
    return pg.locator(f'{panel} .slide:has(input[aria-label="{label}"]) output').first.inner_text()
with sync_playwright() as p:
    b = p.webkit.launch() if WK else p.chromium.launch(args=['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'])
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, has_touch=True, accept_downloads=True)
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append('PAGEERR ' + str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
    pg.goto('file:///home/claude/canva-lite/dist/artifact.html'); pg.wait_for_timeout(800)
    pg.set_input_files('#img', files=['/tmp/claude-0/test.png']); pg.wait_for_timeout(900)
    pg.click('[data-act="edit"]'); pg.wait_for_timeout(500)
    base = px(pg)
    print('tabs', pg.locator('[data-ed-tab]').all_inner_texts(), 'light', pg.locator('[data-sliders="light"] .slide-name').all_inner_texts())
    L = '[data-sliders="light"]'
    pg.locator(f'{L} input[aria-label="Exposure"]').fill('1'); pg.locator(f'{L} input[aria-label="Exposure"]').dispatch_event('change'); pg.wait_for_timeout(800)
    print('exposure shows', val(pg, L, 'Exposure'), 'brighter', sum(px(pg)) > sum(base))
    pg.locator(f'{L} .slide:has(input[aria-label="Contrast"]) output').click(); pg.keyboard.type('35'); pg.keyboard.press('Enter'); pg.wait_for_timeout(300)
    print('typed contrast', val(pg, L, 'Contrast'), 'undo enabled', pg.is_enabled('#ed-undo'))
    pg.click('#ed-undo'); pg.wait_for_timeout(300); print('undo -> contrast', val(pg, L, 'Contrast'))
    pg.click('#ed-redo'); pg.wait_for_timeout(300); print('redo -> contrast', val(pg, L, 'Contrast'))
    # curve: parametric sliders, then a point
    pg.click('#curve-btn'); pg.wait_for_timeout(200)
    pg.locator('#para-sliders input[aria-label="Shadows"]').fill('40'); pg.wait_for_timeout(200)
    pg.click('[data-ch="ToneCurvePV2012"]')
    pg.locator('#curve').scroll_into_view_if_needed(); box = pg.locator('#curve').bounding_box()
    pg.mouse.move(box['x'] + box['width'] * .5, box['y'] + box['height'] * .5); pg.mouse.down()
    pg.mouse.move(box['x'] + box['width'] * .5, box['y'] + box['height'] * .3, steps=5); pg.mouse.up(); pg.wait_for_timeout(300)
    print('curve modes marked', pg.locator('#curve-ch .changed').all_inner_texts())
    pg.screenshot(path='/tmp/claude-0/e-light.png')
    # color: mix, grading wheel, calibration, B&W
    pg.click('[data-ed-tab="color"]'); pg.wait_for_timeout(200)
    pg.locator('[data-sliders="wb"] input[aria-label="Temp"]').fill('25')
    pg.click('[data-csub="mix"]'); pg.click('#bands [data-band="Blue"]')
    pg.locator('#mix-sliders input[aria-label="Saturation"]').fill('-80')
    pg.click('[data-csub="grading"]'); pg.click('#ranges [data-wheel="Shadow"]'); pg.wait_for_timeout(200)
    pg.locator('#wheel').scroll_into_view_if_needed(); wb = pg.locator('#wheel').bounding_box()
    pg.mouse.click(wb['x'] + wb['width'] * .2, wb['y'] + wb['height'] * .5); pg.wait_for_timeout(300)
    print('wheel -> hue', val(pg, '#grade-sliders', 'Hue'), 'sat', val(pg, '#grade-sliders', 'Saturation'))
    pg.click('[data-csub="calibration"]'); pg.locator('[data-sliders="calibration"] input[aria-label="Blue Saturation"]').fill('30'); pg.wait_for_timeout(300)
    print('color subs marked', pg.locator('[data-csub].changed').all_inner_texts())
    pg.screenshot(path='/tmp/claude-0/e-color.png')
    pg.click('#ed-mono'); pg.wait_for_timeout(400)
    r, g, bb = px(pg); print('B&W is grey', max(r, g, bb) - min(r, g, bb) <= 3)
    pg.click('[data-csub="mix"]'); print('B&W mix sliders', pg.locator('#gray-sliders .slide').count(), pg.inner_text('#mix-h'))
    pg.click('#ed-mono')
    # effects, detail, optics, geometry
    pg.click('[data-ed-tab="effects"]'); pg.locator('[data-sliders="vignette"] input[aria-label="Vignette"]').fill('-40'); pg.select_option('#vig-style', '3')
    pg.locator('[data-sliders="grain"] input[aria-label="Grain"]').fill('30')
    pg.click('[data-ed-tab="detail"]'); pg.locator('[data-sliders="sharpen"] input[aria-label="Sharpening"]').fill('60')
    pg.click('[data-ed-tab="optics"]'); pg.locator('[data-sliders="optics"] input[aria-label="Distortion"]').fill('20')
    pg.click('[data-ed-tab="geometry"]'); pg.locator('[data-sliders="geometry"] input[aria-label="Vertical"]').fill('-15'); pg.wait_for_timeout(500)
    print('geometry rotate shows', val(pg, '[data-sliders="geometry"]', 'Rotate'), 'scale', val(pg, '[data-sliders="geometry"]', 'Scale'))
    pg.screenshot(path='/tmp/claude-0/e-geo.png')
    # presets: import .xmp; it sets its settings; Amount 50 blends
    pg.click('[data-ed-tab="presets"]'); pg.wait_for_timeout(500)
    print('built-in thumbs', pg.locator('#filters .chip.th').count())
    pg.set_input_files('#pimport', files=[FIX]); pg.wait_for_timeout(900)
    print('group', pg.input_value('#pgroup'), 'amount shown', pg.is_visible('#amount'))
    pg.click('[data-ed-tab="light"]'); print('exposure after preset', val(pg, L, 'Exposure'))
    pg.click('[data-ed-tab="presets"]'); pg.locator('#amt-range').fill('50'); pg.wait_for_timeout(300)
    pg.click('[data-ed-tab="light"]'); print('exposure at amount 50', val(pg, L, 'Exposure'))
    pg.click('[data-ed-tab="presets"]'); pg.click('[data-pmode="profiles"]'); pg.wait_for_timeout(300)
    print('profiles', pg.locator('#profile-area .chip').all_inner_texts())
    pg.click('[data-pmode="presets"]')
    pg.screenshot(path='/tmp/claude-0/e-presets.png')
    # ⋯ menu: create preset with chosen groups, copy settings
    pg.click('#ed-more'); pg.click('[data-ed-menu="preset"]'); pg.wait_for_timeout(200)
    pg.fill('#ed-dialog-fields input[data-field="name"]', 'Smoke look'); pg.fill('#ed-dialog-fields input[data-field="group"]', 'My Looks')
    pg.screenshot(path='/tmp/claude-0/e-dialog.png')
    pg.click('#ed-dialog-ok'); pg.wait_for_timeout(300)
    print('group now', pg.input_value('#pgroup'))
    pg.click('#ed-more'); pg.click('[data-ed-menu="copy"]'); pg.click('#ed-dialog-ok')
    with pg.expect_download() as d:
        pg.click('#pmanage-btn'); pg.click('#pexport-all')
    z = zipfile.ZipFile(io.BytesIO(open(d.value.path(), 'rb').read())); x = z.read(z.namelist()[-1]).decode()
    print('zip', z.namelist(), 'calibration in xmp', 'crs:BlueSaturation="+30"' in x, 'geometry left out', 'PerspectiveVertical' not in x)
    pg.click('#ed-done'); pg.wait_for_timeout(600)
    saved = pg.evaluate("""() => new Promise(r => { const q = indexedDB.open('canva-lite'); q.onsuccess = () => { const g = q.result.transaction('designs').objectStore('designs').getAll(); g.onsuccess = () => r(g.result[0].pages[0].objects.find(o => o.type === 'image').edit); }; })""")
    print('saved dev keys', len(saved['dev']), 'has preset field', 'preset' in saved, 'filter type', pg.evaluate("1"))
    # a second photo: Previous, then Paste
    pg.set_input_files('#img', files=['/tmp/claude-0/test.png']); pg.wait_for_timeout(900)
    pg.click('[data-act="edit"]'); pg.wait_for_timeout(400)
    pg.click('#ed-more'); pg.click('[data-ed-menu="previous"]'); pg.wait_for_timeout(300)
    print('previous -> exposure', val(pg, L, 'Exposure'))
    pg.click('#ed-more'); pg.click('[data-ed-menu="reset"]'); pg.wait_for_timeout(200); print('reset -> exposure', val(pg, L, 'Exposure'))
    pg.click('#ed-more'); pg.click('[data-ed-menu="paste"]'); pg.wait_for_timeout(300); print('paste -> exposure', val(pg, L, 'Exposure'))
    pg.click('#ed-cancel'); pg.wait_for_timeout(300)
    b.close()
print('errors', errs)
